// An explanatory topology, not an importable n8n workflow. The refresh, chat and
// review executions are independent; the active Qdrant alias and question log
// carry data between them.
const node = (
  id: string,
  label: string,
  type: N8nNodeType,
  x: number,
  y: number,
  extra: Partial<GraphNode> = {},
): GraphNode => ({ id, label, type, version: N8N_NODE_TYPES[type].version, x, y, ...extra });
const main = (id: string, from: string, to: string, path: string, output = 0): GraphEdge => ({
  id,
  kind: "main",
  from: { node: from, index: output },
  to: { node: to, index: 0 },
  path,
});

